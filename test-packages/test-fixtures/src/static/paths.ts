/**
 * Resolved paths for the static fixture sets shipped by `@podkit/test-fixtures`.
 *
 * Consumers should never hard-code paths to fixtures from the repo root. Use
 * the accessors here so the location is owned by this package and survives
 * future moves.
 *
 * The package root is discovered at runtime by walking up from this file's
 * location and looking for the `@podkit/test-fixtures` package.json. This
 * works for both the source path (test-packages/test-fixtures/src/static/) and
 * the bundled `dist/lib.js` output.
 *
 * @module
 */

import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_NAME = '@podkit/test-fixtures';

let cachedRoot: string | null = null;

/**
 * Locate the test-fixtures package root by walking up from the current file
 * looking for a `package.json` whose `name` matches.
 *
 * The result is cached so the directory walk runs at most once per process.
 */
function findPackageRoot(): string {
  if (cachedRoot !== null) return cachedRoot;

  let dir = dirname(fileURLToPath(import.meta.url));
  // Hard cap on walk depth to avoid infinite loops on broken filesystems.
  for (let i = 0; i < 16; i++) {
    const pkgPath = join(dir, 'package.json');
    if (existsSync(pkgPath)) {
      try {
        const pkg = JSON.parse(readFileSync(pkgPath, 'utf8')) as { name?: string };
        if (pkg.name === PACKAGE_NAME) {
          cachedRoot = dir;
          return dir;
        }
      } catch {
        // unparseable package.json — keep walking
      }
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }

  throw new Error(
    `Could not locate ${PACKAGE_NAME} package root by walking up from ${dirname(
      fileURLToPath(import.meta.url)
    )}`
  );
}

/**
 * Absolute path to the package-owned `fixtures/` directory.
 *
 * Outputs of the static generators land here. The directory is gitignored
 * and regenerated on demand via the `generate-static-fixtures` script.
 */
export function getStaticFixturesRoot(): string {
  return join(findPackageRoot(), 'fixtures');
}

/**
 * Path to the multi-format audio fixture set.
 *
 * Contents (regenerated by `generate-static-fixtures --only multi-format`):
 * 01-wav-track.wav, 02-aiff-track.aiff, 03-flac-track.flac,
 * 04-alac-track.m4a, 05-mp3-track.mp3, 06-aac-track.m4a,
 * 07-ogg-track.ogg, 08-opus-track.opus
 */
export function getMultiFormatFixturesDir(): string {
  return join(getStaticFixturesRoot(), 'audio', 'multi-format');
}

