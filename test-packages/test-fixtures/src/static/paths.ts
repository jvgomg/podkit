/**
 * Names of the static fixture sets, used by `ensureFixturesExist` and by
 * `scripts/generate-static-fixtures.ts --only <set>`.
 */
export type StaticFixtureSet =
  | 'multi-format'
  | 'multi-format-embedded'
  | 'multi-format-embedded-alt'
  | 'multi-format-embedded-stripped'
  | 'multi-format-embedded-hires'
  | 'multi-format-compilation'
  | 'multi-format-sidecar'
  | 'multi-format-both'
  | 'goldberg-selections'
  | 'synthetic-tests'
  | 'video';

/**
 * Lookup table from set name to absolute directory.
 */
const SET_DIR: Record<StaticFixtureSet, () => string> = {
  'multi-format': getMultiFormatFixturesDir,
  'multi-format-embedded': getMultiFormatEmbeddedFixturesDir,
  'multi-format-embedded-alt': getMultiFormatEmbeddedAltFixturesDir,
  'multi-format-embedded-stripped': getMultiFormatEmbeddedStrippedFixturesDir,
  'multi-format-embedded-hires': getMultiFormatEmbeddedHiresFixturesDir,
  'multi-format-compilation': getMultiFormatCompilationFixturesDir,
  'multi-format-sidecar': getMultiFormatSidecarFixturesDir,
  'multi-format-both': getMultiFormatBothFixturesDir,
  'goldberg-selections': getGoldbergFixturesDir,
  'synthetic-tests': getSyntheticTestsFixturesDir,
  video: getVideoFixturesDir,
};

/**
 * Sentinel file written by each generator after every track has been
 * produced. `ensureFixturesExist` checks for this rather than any
 * individual fixture file, so a partial output (e.g. ffmpeg crash mid-run)
 * leaves the sentinel absent and the next preflight fails loudly.
 *
 * The file itself is written by `writeGeneratedSentinel` in `shared.ts`
 * and is the last line of each generator function.
 */
const SENTINEL_FILENAME = '.generated';

/**
 * Throw with an actionable message if the named fixture set has not been
 * generated yet.
 *
 * Tests that depend on a static fixture should call this at module load:
 *
 * ```ts
 * import { ensureFixturesExist } from '@podkit/test-fixtures';
 * ensureFixturesExist('multi-format');
 * ```
 *
 * Turbo runs `generate-static-fixtures` automatically as a `test:integration`
 * dependency, so the check is normally a no-op. It only fires when a test is
 * run outside the turbo graph (e.g. `bun test path/to/file.test.ts` directly)
 * against a clean checkout.
 */
export function ensureFixturesExist(set: StaticFixtureSet): void {
  const dir = SET_DIR[set]();
  const sentinel = join(dir, SENTINEL_FILENAME);
  if (!existsSync(sentinel)) {
    throw new Error(
      `Test fixture set '${set}' is missing or incomplete at ${dir}.\n` +
        `Run \`bun run --filter @podkit/test-fixtures generate-static-fixtures\` to (re)generate it.`
    );
  }
}
